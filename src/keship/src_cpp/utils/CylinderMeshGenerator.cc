MeshDataSimple GenerateCylinderMesh(double _radius, double _length, int _segments)
{
  if (_segments < 3) _segments = 3;
  if (_radius <= 0.0 || _length <= 0.0)
  {
    std::cerr << "CylinderMeshGenerator: 半径和长度必须为正数" << std::endl;
    return {};
  }
  CylinderParams p{_radius, _length, _segments};
  return GeneratePrimitiveMesh(PrimitiveType::Cylinder, nullptr, &p);
}

bool GenerateCylinderObjFile(double _radius, double _length, int _segments, const std::string &_filePath)
{
  if (_segments < 3) _segments = 3;
  if (_radius <= 0.0 || _length <= 0.0)
    return false;

  std::ofstream file(_filePath);
  if (!file.is_open())
    return false;

  const double halfLen = _length * 0.5;

  file << "# Cylinder mesh generated by keship\n";

  /// 顶点：0=topCenter, 1=bottomCenter, 2..2+S-1=topEdge, 2+S..2+2S-1=bottomEdge
  file << "v 0 0 " << halfLen << "\n";       // 0: topCenter
  file << "v 0 0 " << -halfLen << "\n";      // 1: bottomCenter
  for (int i = 0; i < _segments; i++)
  {
    double angle = 2.0 * M_PI * i / _segments;
    file << "v " << _radius * std::cos(angle) << " " << _radius * std::sin(angle) << " " << halfLen << "\n";
  }
  for (int i = 0; i < _segments; i++)
  {
    double angle = 2.0 * M_PI * i / _segments;
    file << "v " << _radius * std::cos(angle) << " " << _radius * std::sin(angle) << " " << -halfLen << "\n";
  }

  auto topIdx = [](int i) -> int { return 3 + i; };
  auto bottomIdx = [](int i, int S) -> int { return 3 + S + i; };

  /// 顶盖（逆时针朝上）
  for (int i = 0; i < _segments; i++)
    file << "f 1 " << topIdx(i) << " " << topIdx((i + 1) % _segments) << "\n";

  /// 底盖（逆时针朝下）
  for (int i = 0; i < _segments; i++)
    file << "f 2 " << bottomIdx((i + 1) % _segments, _segments) << " " << bottomIdx(i, _segments) << "\n";

  /// 侧壁
  for (int i = 0; i < _segments; i++)
  {
    int t0 = topIdx(i);
    int t1 = topIdx((i + 1) % _segments);
    int b0 = bottomIdx(i, _segments);
    int b1 = bottomIdx((i + 1) % _segments, _segments);
    file << "f " << t0 << " " << b0 << " " << t1 << "\n";
    file << "f " << b0 << " " << b1 << " " << t1 << "\n";
  }

  file.close();
  std::cout << "CylinderMeshGenerator: OBJ文件生成成功: " << _filePath << std::endl;
  return true;
}

bool WriteMeshToObjFile(const MeshDataSimple &_mesh, const std::string &_filePath)
{
  if (_mesh.vertices.empty() || _mesh.triangles.empty())
    return false;

  std::ofstream file(_filePath);
  if (!file.is_open())
    return false;

  file << "# Mesh generated by keship\n";
  for (const auto &v : _mesh.vertices)
    file << "v " << v.X() << " " << v.Y() << " " << v.Z() << "\n";

  /// 三角形顶点存储的是副本，使用浮点坐标比较建立索引映射
  for (const auto &tri : _mesh.triangles)
  {
    int i0 = -1, i1 = -1, i2 = -1;
    for (size_t j = 0; j < _mesh.vertices.size(); j++)
    {
      if (tri.v0 == _mesh.vertices[j]) i0 = static_cast<int>(j);
      if (tri.v1 == _mesh.vertices[j]) i1 = static_cast<int>(j);
      if (tri.v2 == _mesh.vertices[j]) i2 = static_cast<int>(j);
      if (i0 >= 0 && i1 >= 0 && i2 >= 0) break;
    }
    file << "f " << (i0 + 1) << " " << (i1 + 1) << " " << (i2 + 1) << "\n";
  }

  file.close();
  std::cout << "CylinderMeshGenerator: OBJ文件写入成功: " << _filePath << std::endl;
  return true;
}

